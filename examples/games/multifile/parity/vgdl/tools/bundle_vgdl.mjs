#!/usr/bin/env node
// Bundle one VGDL game (spec + its levels) with the engine into a single PlayTrain game file.
//   node tools/bundle_vgdl.mjs <corpus> <game> [--block N] [--render exact|fast] [--level i] [--out path]
// corpus: vgfmri | infer   (games/<corpus>/<game>.txt and <game>_lvl*.txt)
// Plain concatenation of src/*.js in name order after a constants header; no modules.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import { compileVgdl } from './compile_vgdl.mjs';
const sha = (t) => createHash('sha256').update(t).digest('hex');
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const args = process.argv.slice(2);
const corpus = args[0], game = args[1];
if (!corpus || !game) { console.error('usage: bundle_vgdl.mjs <corpus> <game> [--block N] [--render exact|fast] [--level i] [--out path]'); process.exit(2); }
const opt = (name, dflt) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : dflt; };
const block = parseInt(opt('block', corpus === 'infer' ? '50' : corpus === 'vgfmri_rcrl' ? '30' : '1'), 10);
const render = opt('render', 'fast');
const profile = opt('profile', corpus === 'vgfmri_rcrl' ? 'rcrl' : 'colas');
const level = opt('level', null);
const gdir = join(ROOT, 'games', corpus);
const spec = readFileSync(join(gdir, game + '.txt'), 'utf8');
const lvlFiles = readdirSync(gdir).filter(f => f.startsWith(game + '_lvl') && f.endsWith('.txt'))
  .sort((a, b) => parseInt(a.match(/_lvl(\d+)/)[1], 10) - parseInt(b.match(/_lvl(\d+)/)[1], 10));
if (lvlFiles.length === 0) { console.error('no levels for ' + game); process.exit(2); }
const levels = lvlFiles.map(f => readFileSync(join(gdir, f), 'utf8'));
const srcs = readdirSync(join(ROOT, 'src')).filter(f => f.endsWith('.js')).sort();
let out = `// vgdl/${corpus}/${game} — GENERATED by tools/bundle_vgdl.mjs, do not edit.\n`;
out += `// reference: py-vgdl (see manifest.json); block=${block} render=${render} levels=${levels.length}\n`;
out += `const VG_GAME_TEXT = ${JSON.stringify(spec)};\n`;
out += `const VG_LEVELS = ${JSON.stringify(levels)};\n`;
out += `const VG_BLOCK = ${block};\n`;
out += `const VG_LEVEL_MODE = ${JSON.stringify(level == null ? 'seed' : 'fixed')};\n`;
out += `const VG_LEVEL_INDEX = ${level == null ? 0 : parseInt(level, 10)};\n`;
out += `const VG_RENDER = ${JSON.stringify(render)};\n`;
out += `const VG_PROFILE = ${JSON.stringify(profile)};\n`;
// RC_RL assembles abstract sprite groups in Python 2 dict order; captured from the oracle per game
const gfile = join(gdir, game + '.groups.json');
out += `const VG_GROUP_ORDER = ${existsSync(gfile) ? readFileSync(gfile, 'utf8').trim() : 'null'};\n`;
for (const f of srcs) out += `\n// ---- src/${f} ----\n` + readFileSync(join(ROOT, 'src', f), 'utf8');
// compile pass (option 2): a game-specific tick over the shared runtime; --no-compile keeps the interpreter
const compiled = !args.includes('--no-compile');
if (compiled) out += '\n' + compileVgdl(out);
const name = `vgdl_${game}` + (level == null ? '' : `_lvl${level}`);
const dest = opt('out', join(ROOT, 'dist', name + '.js'));
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
// sidecar: what tools read instead of branching on the directory (multifile README)
if (args.includes('--sidecar')) {
  const manifest = JSON.parse(readFileSync(join(ROOT, 'manifest.json'), 'utf8'));
  const corp = manifest.corpora[corpus] || {};
  const spaces = JSON.parse(readFileSync(join(ROOT, '..', '..', '..', '..', '..', 'runtime', 'action_spaces.json'), 'utf8'));
  const side = {
    name, version: manifest.version, title: `VGDL ${game}`, family: 'vgdl', corpus, game,
    block_size: block, profile, compiled, levels: levels.length, level_mode: level == null ? 'seed' : 'fixed', render: render,
    action_space: manifest.action_space, actions: spaces[manifest.action_space],
    max_steps: manifest.max_steps, obs: manifest.obs, human: manifest.human,
    parity: !!corp.parity, reference: corp.reference || null, status: corp.status || null,
    source_sha256: { spec: sha(spec), levels: levels.map(sha) },
  };
  writeFileSync(dest.replace(/\.js$/, '.json'), JSON.stringify(side, null, 2) + '\n');
}
console.log(dest);
