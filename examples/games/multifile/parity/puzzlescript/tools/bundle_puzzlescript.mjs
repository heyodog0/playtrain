#!/usr/bin/env node
// Bundle one PuzzleScript game with the vendored reference engine into a single PlayTrain game file.
//   node tools/bundle_puzzlescript.mjs <game> [--out path] [--sidecar]
// Plain concatenation, in scope order: a constants header (game text + def), src/0*.js (shims), reference/js/* in the
// reference's own load order (manifest reference.engine_load_order), src/9*.js (prelude). Never edits reference/.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = join(HERE, '..');
const args = process.argv.slice(2);
const game = args[0];
if (!game || game.startsWith('--')) { console.error('usage: bundle_puzzlescript.mjs <game> [--out path] [--sidecar]'); process.exit(2); }
const opt = (n, d) => { const i = args.indexOf('--' + n); return i >= 0 ? args[i + 1] : d; };
const sha256 = (t) => createHash('sha256').update(t).digest('hex');
const manifest = JSON.parse(readFileSync(join(ROOT, 'manifest.json'), 'utf8'));
const def = JSON.parse(readFileSync(join(ROOT, 'games', game + '.json'), 'utf8'));
const text = readFileSync(join(ROOT, 'games', game + '.txt'), 'utf8');
if (sha256(text) !== def.sha256 || manifest.corpus.games[game].sha256 !== def.sha256) { console.error(`${game}: games/${game}.txt sha256 disagrees with its def / the manifest`); process.exit(1); }
for (const rel of manifest.reference.engine_load_order) if (sha256(readFileSync(join(ROOT, 'reference', rel))) !== manifest.vendored[rel].sha256) { console.error(`vendored ${rel} does not match manifest sha256`); process.exit(1); }
const srcs = readdirSync(join(ROOT, 'src')).filter(f => f.endsWith('.js')).sort();
const sources = [...srcs.filter(f => f < '9').map(f => ['src/' + f, join(ROOT, 'src', f)]), ...manifest.reference.engine_load_order.map(f => ['reference/' + f, join(ROOT, 'reference', f)]), ...srcs.filter(f => f >= '9').map(f => ['src/' + f, join(ROOT, 'src', f)])];
const name = `ps_${game}`;
let out = `// ${name} — GENERATED by tools/bundle_puzzlescript.mjs, do not edit.\n`;
out += `// reference: PuzzleScript ${manifest.reference.commit.slice(0, 12)} (engine vendored verbatim, see manifest.json); game ${def.source} sha256 ${def.sha256.slice(0, 12)}\n`;
out += `const PS_GAME_TEXT = ${JSON.stringify(text)};\n`;
out += `const PS_GAME_DEF = ${JSON.stringify(def)};\n`;
for (const [rel, p] of sources) out += `\n// ---- ${rel} ----\n` + readFileSync(p, 'utf8') + '\n';
const dest = opt('out', join(ROOT, 'dist', name + '.js'));
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
if (args.includes('--sidecar')) {
  const actions = [{ name: 'UP', held: [38], press: null }, { name: 'LEFT', held: [37], press: null }, { name: 'DOWN', held: [40], press: null },
    { name: 'RIGHT', held: [39], press: null }, { name: 'ACTION', held: [88], press: null }, { name: 'NOOP', held: [], press: null }];
  const side = {
    name, version: manifest.version, title: `PuzzleScript ${def.title}`, family: 'puzzlescript', game, author: def.author, source: def.source,
    action_space: 'ps6', actions, level_mode: def.level_mode, playable_levels: def.playable_levels, levels: def.levels, metadata_keys: def.metadata_keys,
    max_steps: manifest.max_steps, obs: manifest.obs,
    human: { steps_per_second: manifest.human.steps_per_second, controls: def.human.controls, keymap_overlay: true },
    parity: true, reference: manifest.reference, source_sha256: sha256(out),
  };
  writeFileSync(dest.replace(/\.js$/, '.json'), JSON.stringify(side, null, 2) + '\n');
}
console.log(dest);
