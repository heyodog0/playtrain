#!/usr/bin/env node
// Bundle one CHIP-8 game (its games/<game>.json + ROM) with the CPU into a single PlayTrain game file.
//   node tools/bundle_chip8.mjs <game> [--out path] [--sidecar]
// Plain concatenation: a constants header, ../../common/threefry2x32.js, then src/*.js in name order
// (the same list as tests/conftest.py SOURCES). No modules. The ROM is inlined as base64 and its sha1
// checked against games/<game>.json and manifest.json first.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const args = process.argv.slice(2);
const game = args[0];
if (!game || game.startsWith('--')) { console.error('usage: bundle_chip8.mjs <game> [--out path] [--sidecar]'); process.exit(2); }
const opt = (name, dflt) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : dflt; };
const sha1 = (b) => createHash('sha1').update(b).digest('hex');
const sha256 = (t) => createHash('sha256').update(t).digest('hex');

const manifest = JSON.parse(readFileSync(join(ROOT, 'manifest.json'), 'utf8'));
const def = JSON.parse(readFileSync(join(ROOT, 'games', game + '.json'), 'utf8'));
const rom = readFileSync(join(ROOT, 'roms', def.rom));
if (sha1(rom) !== def.sha1) { console.error(`${game}: roms/${def.rom} sha1 ${sha1(rom)} != games/${game}.json ${def.sha1}`); process.exit(1); }
if (manifest.roms[def.rom].sha1 !== def.sha1) { console.error(`${game}: manifest.json roms["${def.rom}"] disagrees with games/${game}.json`); process.exit(1); }

const sources = [join(ROOT, '..', '..', 'common', 'threefry2x32.js'), ...readdirSync(join(ROOT, 'src')).filter(f => f.endsWith('.js')).sort().map(f => join(ROOT, 'src', f))];
const name = `chip8_${game}`;
let out = `// ${name} — GENERATED by tools/bundle_chip8.mjs, do not edit.\n`;
out += `// reference: Octax ${manifest.reference.commit.slice(0, 12)} (see manifest.json); rom ${def.rom} sha1 ${def.sha1}\n`;
out += `const C8_GAME_DEF = ${JSON.stringify(def)};\n`;
out += `const C8_ROM_B64 = ${JSON.stringify(rom.toString('base64'))};\n`;
for (const p of sources) out += `\n// ---- ${p.includes('/common/') ? '../../common/' : 'src/'}${p.split('/').pop()} ----\n` + readFileSync(p, 'utf8');
const dest = opt('out', join(ROOT, 'dist', name + '.js'));
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);

if (args.includes('--sidecar')) {
  const KEYCODES = [88, 49, 50, 51, 81, 87, 69, 65, 83, 68, 90, 67, 52, 82, 70, 86];
  const KEYNAMES = ['X', '1', '2', '3', 'Q', 'W', 'E', 'A', 'S', 'D', 'Z', 'C', '4', 'R', 'F', 'V'];
  const actions = def.action_set.map(k => ({ name: `KEY_${k.toString(16).toUpperCase()}`, held: [KEYCODES[k]], press: null }));
  actions.push({ name: 'NOOP', held: [], press: null });
  const side = {
    name, version: manifest.version, title: `CHIP-8 ${def.title}`, family: 'chip8', game, env_id: def.env_id || game,
    module: def.module, authors: def.authors, release: def.release,
    rom: { file: def.rom, sha1: def.sha1 },
    action_space: `chip8_${game}`, actions,
    action_set: def.action_set, startup_instructions: def.startup_instructions, custom_startup: def.custom_startup, disable_delay: !!def.disable_delay,
    max_steps: manifest.max_steps, obs: manifest.obs,
    human: { steps_per_second: manifest.human.steps_per_second, controls: def.human.controls, keymap_overlay: true,
             keys: Object.fromEntries(def.action_set.map(k => [KEYNAMES[k], `CHIP-8 key ${k.toString(16).toUpperCase()}: ${def.human.keys[String(k)] || ''}`])) },
    parity: true, reference: manifest.reference,
    source_sha256: sha256(out),
  };
  writeFileSync(dest.replace(/\.js$/, '.json'), JSON.stringify(side, null, 2) + '\n');
}
console.log(dest);
